// server.js -- PC-hosted Node.js server.
// Runs the simulated audio generation on the PC and transmits 
// 48-byte binary UDP packets directly to the ESP32-S3 at 60 Hz.

const http = require('http');
const fs = require('fs');
const path = require('path');
const dgram = require('dgram');
const dns = require('dns');
const net = require('net');

// --- Configuration ---
// ESP32 address: its mDNS name by default, or `node server.js <host-or-ip>`,
// or update it from the UI. The ESP32 prints both on the serial monitor at boot.
let ESP32_HOST = process.argv[2] || 'visualizer.local';
const UDP_PORT = 49152;
const HTTP_PORT = 3000;
const RESOLVE_INTERVAL_MS = 30000;

// --- Host resolution ---
// An mDNS lookup can take tens of ms or fail outright, far too slow to do on
// every 16 ms send. Resolve once, cache the IP, and refresh it periodically
// (DHCP may move the board) or right away after a failed send.
let ESP32_IP = null;
let resolving = false;

function resolveHost() {
  if (resolving) return;
  if (beaconFresh() && !net.isIP(ESP32_HOST)) return; // beacon is authoritative
  resolving = true;
  const host = ESP32_HOST;
  dns.lookup(host, { family: 4 }, (err, address) => {
    resolving = false;
    if (host !== ESP32_HOST) return resolveHost(); // host changed mid-lookup
    // A beacon arrived while this lookup was in flight; it is fresher than the
    // answer (or failure) of the lookup, so don't let mDNS overwrite it.
    if (beaconFresh() && !net.isIP(host)) return;
    if (err) {
      if (ESP32_IP !== null) console.log(`Lost ${host}: ${err.code}`);
      else console.log(`Cannot resolve ${host} (${err.code}), retrying...`);
      ESP32_IP = null;
      return;
    }
    if (address !== ESP32_IP) console.log(`${host} -> ${address}`);
    ESP32_IP = address;
  });
}

function setHost(host) {
  ESP32_HOST = host;
  ESP32_IP = null;
  lastBeaconAt = 0; // a newly chosen target must be re-resolved, not beacon-trusted
  resolveHost();
}

// --- Beacon listener ---
// The ESP32 broadcasts "VIZ1" every 2 s and on every (re)connect. The packet's
// source address is the board's current IP, so a DHCP change is picked up in
// seconds with no mDNS. mDNS stays as the fallback (e.g. a firewall blocking
// inbound UDP, or no beacon heard). A manually entered raw IP is never overridden.
const BEACON_PORT = 49153;
const BEACON_FRESH_MS = 8000;
let lastBeaconAt = 0;

const beaconSocket = dgram.createSocket({ type: 'udp4', reuseAddr: true });
beaconSocket.on('message', (msg, rinfo) => {
  if (msg.toString() !== 'VIZ1') return;
  if (net.isIP(ESP32_HOST)) return; // user pinned an explicit IP
  lastBeaconAt = Date.now();
  if (rinfo.address !== ESP32_IP) {
    console.log(`Beacon: ESP32 is at ${rinfo.address}`);
    ESP32_IP = rinfo.address;
  }
});
beaconSocket.on('error', (e) => console.log(`Beacon listener unavailable (${e.code}); using mDNS only`));
beaconSocket.bind(BEACON_PORT);

function beaconFresh() {
  return Date.now() - lastBeaconAt < BEACON_FRESH_MS;
}

resolveHost();
setInterval(resolveHost, RESOLVE_INTERVAL_MS);

// Shared audio metrics generated by PC simulation
const audioState = {
  bands: new Float32Array(8),
  level: 0.0,
  bass: 0.0,
  mid: 0.0,
  treb: 0.0
};

// --- UDP Audio Streamer ---
const udpSocket = dgram.createSocket('udp4');
const t0 = Date.now();

// 60 Hz update loop (~16.6 ms)
setInterval(() => {
  const t = (Date.now() - t0) / 1000.0;

  // Replicate the simulated audio generator from the original preview
  for (let b = 0; b < 8; b++) {
    audioState.bands[b] = 0.5 + 0.5 * Math.sin(t * (1.3 + b * 0.4) + b);
  }
  audioState.bass  = (audioState.bands[0] + audioState.bands[1]) / 2.0;
  audioState.mid   = (audioState.bands[2] + audioState.bands[3] + audioState.bands[4]) / 3.0;
  audioState.treb  = (audioState.bands[5] + audioState.bands[6] + audioState.bands[7]) / 3.0;
  audioState.level = audioState.bands.reduce((acc, v) => acc + v, 0) / 8.0;

  // Allocate 48-byte buffer matching ESP32 AudioPayload:
  // 12 little-endian IEEE 754 floats (8 bands + level + bass + mid + treb)
  const buf = Buffer.alloc(48);
  for (let i = 0; i < 8; i++) {
    buf.writeFloatLE(audioState.bands[i], i * 4);
  }
  buf.writeFloatLE(audioState.level, 32);
  buf.writeFloatLE(audioState.bass,  36);
  buf.writeFloatLE(audioState.mid,   40);
  buf.writeFloatLE(audioState.treb,  44);

  if (!ESP32_IP) return; // not resolved yet
  udpSocket.send(buf, 0, 48, UDP_PORT, ESP32_IP, (err) => {
    // The board may have moved; look it up again rather than keep failing
    if (err) resolveHost();
  });
}, 16);

// --- HTTP Web Server ---
const server = http.createServer((req, res) => {
  if (req.method === 'GET' && req.url === '/api/audio') {
    res.writeHead(200, { 'Content-Type': 'application/json' });
    return res.end(JSON.stringify({
      bands: Array.from(audioState.bands),
      level: audioState.level,
      bass: audioState.bass,
      mid: audioState.mid,
      treb: audioState.treb
    }));
  }

  if (req.method === 'GET' && req.url === '/api/config') {
    res.writeHead(200, { 'Content-Type': 'application/json' });
    return res.end(JSON.stringify({ host: ESP32_HOST, ip: ESP32_IP }));
  }

  // Body: { host: "visualizer.local" | "192.168.1.77" }. Replies once the
  // lookup finishes, so the UI immediately learns whether the name resolved.
  if (req.method === 'POST' && req.url === '/api/config') {
    let body = '';
    req.on('data', chunk => { body += chunk; });
    req.on('end', () => {
      let host;
      try {
        host = String(JSON.parse(body).host || '').trim();
      } catch (e) {}
      if (!host) {
        res.writeHead(400, { 'Content-Type': 'application/json' });
        return res.end(JSON.stringify({ error: 'expected {"host": "..."}' }));
      }
      setHost(host);
      console.log(`ESP32 target set to: ${host}`);
      dns.lookup(host, { family: 4 }, (err, address) => {
        res.writeHead(200, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({ ok: !err, host, ip: err ? null : address,
                                 error: err ? err.code : undefined }));
      });
    });
    return;
  }

  // Serve static files from /public
  let filePath = path.join(__dirname, 'public', req.url === '/' ? 'index.html' : req.url);
  const ext = path.extname(filePath);
  const mimeTypes = {
    '.html': 'text/html',
    '.js': 'application/javascript',
    '.css': 'text/css',
    '.json': 'application/json'
  };

  fs.readFile(filePath, (err, content) => {
    if (err) {
      res.writeHead(404, { 'Content-Type': 'text/plain' });
      res.end('File not found');
    } else {
      res.writeHead(200, { 'Content-Type': mimeTypes[ext] || 'application/octet-stream' });
      res.end(content);
    }
  });
});

server.listen(HTTP_PORT, () => {
  console.log(`Web server listening at http://localhost:${HTTP_PORT}`);
  console.log(`Streaming simulated UDP audio to ${ESP32_HOST}:${UDP_PORT}`);
});